function makeCell(cellType, source) {
  const lines = Array.isArray(source) ? source : source.split('\n').map((l, i, arr) => i < arr.length - 1 ? l + '\n' : l);
  const formatted = lines.map((l, i) => (i < lines.length - 1 && !l.endsWith('\n')) ? l + '\n' : l);
  const cell = {
    cell_type: cellType,
    metadata: {},
    source: formatted
  };
  if (cellType === 'code') {
    cell.execution_count = null;
    cell.outputs = [];
  }
  return cell;
}

