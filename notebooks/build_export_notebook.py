def make_cell(cell_type, source_lines):
    if isinstance(source_lines, str):
        source_lines = [source_lines]
    # Ensure all lines end with \n except possibly the last
    formatted = []
    for i, line in enumerate(source_lines):
        if i < len(source_lines) - 1 and not line.endswith("\n"):
            formatted.append(line + "\n")
        else:
            formatted.append(line)
    
    cell = {
        "cell_type": cell_type,
        "metadata": {},
        "source": formatted
    }
    if cell_type == "code":
        cell["execution_count": None] = None
        cell["outputs"] = []
    return cell

